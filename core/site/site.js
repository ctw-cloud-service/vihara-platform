/**
 * ============================================================================
 * 函式名稱：切換分頁
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：
 *   顯示指定分頁、隱藏其他分頁，並把分頁名稱記在網址 #（重新整理或分享網址時停在同一頁）。
 *   該分頁第一次顯示時才向後端讀取資料。
 * 參數：
 *   str區塊       {string}  區塊名稱，例如「人員與權限」
 *   bool移焦點    {boolean} 選填，true 時把鍵盤焦點移到該標籤（方向鍵切換時使用）
 * 傳回：無
 * ============================================================================
 */
function 切換分頁(str區塊, bool移焦點) {
  // 不認得的名稱：不處理
  if (arr區塊名稱.indexOf(str區塊) === -1) return;
  obj頁面狀態.str目前分頁 = str區塊;

  // 標籤：選中的可用 Tab 鍵進入，其餘用方向鍵切換（無障礙標籤的標準做法）
  arr區塊名稱.forEach(function (str名稱) {
    const bool選中 = str名稱 === str區塊;
    const el標籤 = 取得元素(`分頁_${str名稱}`);
    el標籤.setAttribute('aria-selected', bool選中 ? 'true' : 'false');
    el標籤.tabIndex = bool選中 ? 0 : -1;
    取得元素(`面板_${str名稱}`).hidden = !bool選中;
  });
  if (bool移焦點) 取得元素(`分頁_${str區塊}`).focus();

  // 記在網址 #（不新增瀏覽紀錄，按上一頁不會在分頁間跳）
  try {
    window.history.replaceState(null, '', `${window.location.pathname}${window.location.search}#${encodeURIComponent(str區塊)}`);
  } catch (err) { /* 少數環境不允許修改網址，略過不影響使用 */ }

  展開區塊時載入(str區塊);
}


/**
 * ============================================================================
 * 函式名稱：處理分頁按鍵
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：標籤列的鍵盤操作：← → 切換上一個／下一個（頭尾循環），Home／End 到第一個／最後一個。
 * 參數：e {KeyboardEvent}
 * 傳回：無
 * ============================================================================
 */
function 處理分頁按鍵(e) {
  const int目前 = arr區塊名稱.indexOf(obj頁面狀態.str目前分頁);
  const int總數 = arr區塊名稱.length;
  let int目標 = -1;
  if (e.key === 'ArrowRight') int目標 = (int目前 + 1) % int總數;
  else if (e.key === 'ArrowLeft') int目標 = (int目前 - 1 + int總數) % int總數;
  else if (e.key === 'Home') int目標 = 0;
  else if (e.key === 'End') int目標 = int總數 - 1;
  if (int目標 === -1) return;
  e.preventDefault();
  切換分頁(arr區塊名稱[int目標], true);
}


