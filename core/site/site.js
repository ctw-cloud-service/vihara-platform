/**
 * ============================================================================
 * 函式名稱：載入人員與權限
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：同時讀取人員名單與權限選項（兩個請求並行，節省等待時間），再重畫。
 * 參數：無
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 載入人員與權限() {
  const arr結果 = await Promise.all([呼叫平台('精舍.列出人員'), 呼叫平台('精舍.取得權限選項')]);
  obj頁面狀態.arr管理員 = Array.isArray(arr結果[0].arr管理員) ? arr結果[0].arr管理員 : [];
  obj頁面狀態.arr人員 = Array.isArray(arr結果[0].arr人員) ? arr結果[0].arr人員 : [];
  obj頁面狀態.arr權限選項 = Array.isArray(arr結果[1].arr模組) ? arr結果[1].arr模組 : [];
  // 啟用中在前，再依姓名排序
  obj頁面狀態.arr人員.sort(function (a, b) {
    return (a.str狀態 === '啟用' ? 0 : 1) - (b.str狀態 === '啟用' ? 0 : 1) || a.str姓名.localeCompare(b.str姓名);
  });
  畫人員與權限();
}


/**
 * ============================================================================
 * 函式名稱：取得可指派權限清單
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：把權限選項攤平成 { 權限項目: { str模組名稱, str項目 } }，方便查名稱。
 * 參數：無
 * 傳回：{Object}
 * ============================================================================
 */
function 取得可指派權限清單() {
  const obj清單 = {};
  obj頁面狀態.arr權限選項.forEach(function (obj模組) {
    obj模組.arr可指派權限.forEach(function (obj權限) {
      obj清單[obj權限.str權限項目] = { str模組名稱: obj模組.str模組名稱, str項目: obj權限.str項目 };
    });
  });
  return obj清單;
}


