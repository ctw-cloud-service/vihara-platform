/**
 * ============================================================================
 * 函式名稱：啟動精舍設定頁
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：開頁時綁定事件，用保存的工作階段確認身分；沒有或逾時就顯示登入。
 * 參數：無
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 啟動精舍設定頁() {
  // 網址沒有 ?site=：精舍設定一定要指定精舍
  if (!取得網址精舍代號()) {
    切換狀態('載入');
    取得元素('區_載入').textContent = '網址缺少精舍代號。請從精舍的入口頁點「精舍設定」進入。';
    return;
  }

  // 任何請求遇到登入逾時，都回到登入畫面
  設定登入逾時處理(function (str訊息) { 顯示登入(str訊息); });
  綁定事件();

  // 回入口頁的連結帶上精舍代號
  const str入口 = 取得頁面網址('core/', 取得網址精舍代號());
  取得元素('回入口頁').href = str入口;
  取得元素('無權限回入口').href = str入口;

  切換狀態('載入');
  try {
    const obj資訊 = await 取得我的資訊();
    if (obj資訊) {
      進入精舍設定(obj資訊);
    } else {
      顯示登入();
    }
  } catch (err) {
    // 登入逾時已由處理函式切回登入畫面；其他錯誤（例如精舍已停用）顯示在登入畫面
    if (err.str錯誤代碼 !== 'SESSION_EXPIRED') 顯示登入(取得錯誤訊息(err));
  }
}


/**
 * ============================================================================
 * 函式名稱：顯示登入
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：切到登入畫面並畫出 Google 登入按鈕（使用共用 auth.js）。
 * 參數：
 *   str提醒   {string}  選填，例如「登入已逾時」
 *   bool一般  {boolean} 選填，true 表示不是錯誤（例如「已登出」）
 * 傳回：無
 * ============================================================================
 */
function 顯示登入(str提醒, bool一般) {
  取得元素('匾額文字').textContent = '精舍設定';
  document.title = `精舍設定｜${obj平台設定.str平台名稱}`;
  取得元素('登入中').hidden = true;
  顯示訊息(str提醒 || '', bool一般);
  切換狀態('登入');

  顯示Google登入按鈕(
    取得元素('google按鈕'),
    function 成功() {
      顯示訊息('');
      // 登入回應只有身分，統一再取一次我的資訊
      取得我的資訊()
        .then(進入精舍設定)
        .catch(function (err) { 顯示登入(取得錯誤訊息(err)); });
    },
    function 失敗(err) {
      取得元素('登入中').hidden = true;
      顯示訊息(取得錯誤訊息(err));
    },
    function 處理中() {
      顯示訊息('');
      取得元素('登入中').hidden = false;
    }
  );
}


/**
 * ============================================================================
 * 函式名稱：進入精舍設定
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：
 *   確認角色是精舍管理員才顯示設定畫面，否則顯示「只限精舍管理員」。
 *   （真正的權限由後端每個動作檢查，這裡只決定畫面。）
 * 參數：obj資訊 {Object} 後端「驗證.我的資訊」的回應 { obj身分, arr模組 }
 * 傳回：無
 * ============================================================================
 */
function 進入精舍設定(obj資訊) {
  const obj身分 = obj資訊.obj身分 || {};
  obj頁面狀態.obj身分 = obj身分;

  // 匾額顯示精舍名稱
  取得元素('匾額文字').textContent = obj身分.str精舍名稱 || '精舍設定';
  document.title = `精舍設定｜${obj身分.str精舍名稱 || obj平台設定.str平台名稱}`;
  顯示訊息('');

  // 不是精舍管理員：承辦人、或系統管理員誤入
  if (obj身分.str角色 !== '精舍管理員') {
    取得元素('無權限帳號').textContent = obj身分.str帳號 || '';
    取得元素('無權限角色').textContent = obj身分.str角色 || '';
    切換狀態('無權限');
    return;
  }

  取得元素('問候').textContent = `${obj身分.str姓名 || obj身分.str帳號}，您好　`;
  const el角色 = document.createElement('span');
  el角色.className = '小字';
  el角色.textContent = '精舍管理員';
  取得元素('問候').appendChild(el角色);

  // 清空舊資料（換帳號重新登入時）
  obj頁面狀態.obj已載入 = {};
  obj頁面狀態.obj載入中 = {};
  obj頁面狀態.str目前分頁 = '';
  arr區塊名稱.forEach(function (str區塊) { 取得元素(`內容_${str區塊}`).innerHTML = ''; });
  切換狀態('已登入');

  // 一開始顯示哪個分頁：網址 # 有指定就用它（重新整理後停在同一頁），否則從「功能開通」開始
  let str初始 = '';
  try { str初始 = decodeURIComponent(window.location.hash.replace(/^#/, '')); } catch (err) { str初始 = ''; }
  切換分頁(arr區塊名稱.indexOf(str初始) !== -1 ? str初始 : '功能開通');
}


