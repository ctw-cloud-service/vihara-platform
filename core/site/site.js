/**
 * ============================================================================
 * 函式名稱：載入區塊
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：
 *   向後端讀取某區塊的資料並重畫。同一區塊正在讀取時，共用同一次讀取，
 *   不會重複呼叫後端。失敗時丟出錯誤，由呼叫端決定怎麼顯示。
 * 參數：str區塊 {string} 區塊名稱
 * 傳回：{Promise<void>}
 * ============================================================================
 */
function 載入區塊(str區塊) {
  // 已有進行中的讀取：等它完成即可
  if (obj頁面狀態.obj載入中[str區塊]) return obj頁面狀態.obj載入中[str區塊];

  const obj對照 = {
    功能開通: 載入功能開通,
    人員與權限: 載入人員與權限,
    外部檔案: 載入外部檔案,
    共用主檔: 載入共用主檔
  };
  const fn載入 = obj對照[str區塊];
  if (!fn載入) return Promise.resolve();

  const obj讀取 = fn載入()
    .then(function () { obj頁面狀態.obj已載入[str區塊] = true; })
    .finally(function () { delete obj頁面狀態.obj載入中[str區塊]; });
  obj頁面狀態.obj載入中[str區塊] = obj讀取;
  return obj讀取;
}


/**
 * ============================================================================
 * 函式名稱：展開區塊時載入
 * 版本：v1.1.0（2026-10-26）
 *   v1.1.0：改由「切換分頁」呼叫
 * ----------------------------------------------------------------------------
 * 用途：分頁第一次顯示時顯示「讀取中」並載入資料；失敗就在分頁內顯示原因與重試鈕。
 *       已讀過且未過期的分頁不重複讀取。
 * 參數：str區塊 {string} 區塊名稱
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 展開區塊時載入(str區塊) {
  if (obj頁面狀態.obj已載入[str區塊]) return;
  const el內容 = 取得區塊內容(str區塊);
  el內容.innerHTML = '<p class="載入中">正在讀取…</p>';

  await 執行操作(null, function () { return 載入區塊(str區塊); }, function (str訊息) {
    el內容.innerHTML = `<p class="訊息" role="alert">${跳脫HTML(str訊息)}</p>
      <button type="button" class="按鈕 小" data-動作="重新讀取" data-區塊="${跳脫HTML(str區塊)}">重新讀取</button>`;
  });
}


/**
 * ============================================================================
 * 函式名稱：完成區塊操作
 * 版本：v1.1.0（2026-10-26）
 *   v1.1.0：受影響區塊「是否正在顯示」改以目前分頁判斷
 * ----------------------------------------------------------------------------
 * 用途：
 *   區塊內操作的共用流程：
 *     呼叫後端 → 成功後重新讀取該區塊（及受影響的區塊）並重畫 →
 *     把結果訊息顯示在 fn訊息位置 指到的地方（重畫後重新尋找，所以能找到新元素）。
 *   失敗時不重畫（保留已輸入內容），把錯誤顯示在同一位置。
 *   開始時先清除該位置上一次的訊息。
 * 參數：
 *   el按鈕          {HTMLElement} 觸發的按鈕
 *   str動作         {string}      後端 action
 *   obj參數         {Object}      傳給後端的參數
 *   arr重新載入     {string[]}    成功後要重新讀取的區塊（第一個是本區塊）
 *   fn訊息位置      {Function}    傳回要顯示訊息的元素
 * 傳回：{Promise<Object|undefined>} 成功時為後端回應
 * ============================================================================
 */
async function 完成區塊操作(el按鈕, str動作, obj參數, arr重新載入, fn訊息位置) {
  // 先清掉上一次的訊息，避免處理中還看到舊結果而誤會
  顯示區塊訊息(fn訊息位置(), '');
  return 執行操作(el按鈕, async function () {
    const obj結果 = await 呼叫平台(str動作, obj參數);

    // 其他受影響的區塊：標記為過期，切換到該分頁時會重新讀取
    // （目前顯示的分頁一定是本區塊，所以不必立刻讀取其他分頁）
    arr重新載入.slice(1).forEach(function (str區塊) {
      obj頁面狀態.obj已載入[str區塊] = false;
      if (obj頁面狀態.str目前分頁 === str區塊) 展開區塊時載入(str區塊);
    });

    // 本區塊重新讀取並重畫，再顯示結果
    await 載入區塊(arr重新載入[0]);
    顯示區塊訊息(fn訊息位置(), obj結果.str訊息 || '已完成。', true);
    return obj結果;
  }, function (str訊息) {
    顯示區塊訊息(fn訊息位置(), str訊息, false);
  });
}


