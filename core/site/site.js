/**
 * ============================================================================
 * 函式名稱：複製系統帳號
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：把系統帳號複製到剪貼簿，方便貼到試算表的「共用」。
 *       瀏覽器不允許時改為選取文字，請使用者自己按複製。
 * 參數：el按鈕 {HTMLButtonElement}
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 複製系統帳號(el按鈕) {
  const str帳號 = obj平台設定.str系統帳號 || '';
  const str原文字 = el按鈕.textContent;
  try {
    await navigator.clipboard.writeText(str帳號);
    el按鈕.textContent = '已複製';
  } catch (err) {
    // 不支援剪貼簿：選取旁邊的帳號文字
    const el文字 = el按鈕.previousElementSibling;
    if (el文字) {
      const obj範圍 = document.createRange();
      obj範圍.selectNodeContents(el文字);
      const obj選取 = window.getSelection();
      obj選取.removeAllRanges();
      obj選取.addRange(obj範圍);
    }
    el按鈕.textContent = '請按 Ctrl+C';
  }
  setTimeout(function () { if (el按鈕.isConnected) el按鈕.textContent = str原文字; }, 2000);
}


