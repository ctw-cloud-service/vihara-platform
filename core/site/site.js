/**
 * ============================================================================
 * 函式名稱：綁定事件
 * 版本：v1.1.0（2026-10-26）
 *   v1.1.0：加入索引標籤的點選與方向鍵
 * ----------------------------------------------------------------------------
 * 用途：
 *   集中綁定所有事件。四個區塊的內容會重畫，所以一律在「區塊清單」上做事件委派，
 *   重畫後不必重綁。toggle 事件不會冒泡，用捕捉階段。
 * 參數：無
 * 傳回：無
 * ============================================================================
 */
function 綁定事件() {
  // 登出／換帳號
  取得元素('登出按鈕').addEventListener('click', function () { 執行登出(this); });
  取得元素('換帳號按鈕').addEventListener('click', function () { 執行登出(this); });

  const el清單 = 取得元素('區塊清單');

  // ── 索引標籤：點選切換；方向鍵切換 ──
  document.querySelector('.分頁列').addEventListener('click', function (e) {
    const el標籤 = e.target.closest('.分頁[data-區塊]');
    if (el標籤) 切換分頁(el標籤.dataset.區塊);
  });
  document.querySelector('.分頁列').addEventListener('keydown', 處理分頁按鍵);

  // ── 展開：分頁內的項目（承辦人、外部檔案、主檔）一次只展開一個 ──
  el清單.addEventListener('toggle', function (e) {
    const el = e.target;
    if (!el.matches || !el.matches('details')) return;

    // 承辦人
    if (el.dataset.帳號 !== undefined) { 保持展開(el, '人員', el.dataset.帳號); return; }
    // 外部檔案
    if (el.dataset.項目 !== undefined) { 保持展開(el, '外部', el.dataset.項目); return; }
    // 主檔：第一次展開時讀取項目
    if (el.dataset.主檔 !== undefined) {
      保持展開(el, '主檔', el.dataset.主檔);
      const str主檔 = el.dataset.主檔;
      if (el.open && !obj頁面狀態.obj主檔項目[str主檔]) {
        執行操作(null, function () { return 載入主檔項目(str主檔); }, function (str訊息) {
          const el內容 = 取得元素(`主檔內容_${str主檔}`);
          if (el內容) el內容.innerHTML = `<p class="訊息" role="alert">${跳脫HTML(str訊息)}</p>`;
        });
      }
    }
  }, true);

  // ── 按鈕 ──
  el清單.addEventListener('click', function (e) {
    const el按鈕 = e.target.closest('button[data-動作]');
    if (!el按鈕) return;
    const str動作 = el按鈕.dataset.動作;

    if (str動作 === '重新讀取') { 展開區塊時載入(el按鈕.dataset.區塊); return; }
    if (str動作 === '開通模組' || str動作 === '關閉模組') { 處理功能開通按鈕(el按鈕); return; }
    if (str動作 === '停用人員' || str動作 === '啟用人員' || str動作 === '重新同步') { 處理人員按鈕(el按鈕); return; }
    if (str動作 === '複製系統帳號') { 複製系統帳號(el按鈕); }
  });

  // ── 表單 ──
  el清單.addEventListener('submit', function (e) {
    const el表單 = e.target.closest('form[data-表單]');
    if (!el表單) return;
    e.preventDefault();

    switch (el表單.dataset.表單) {
      case '新增人員':
      case '修改人員':
      case '設定權限':
        處理人員表單(el表單);
        break;
      case '登記外部檔案':
        處理外部檔案表單(el表單);
        break;
      case '儲存主檔項目':
      case '新增主檔項目':
        處理主檔表單(el表單);
        break;
      default:
        break;
    }
  });
}


