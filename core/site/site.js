/**
 * ============================================================================
 * 函式名稱：產生承辦人HTML
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：一位承辦人的清單列，展開後可改姓名、停用／啟用、勾選權限。
 *       已關閉功能的權限畫面上看不到也改不到，只顯示「保留中 N 項」。
 * 參數：
 *   obj人員     {Object} { str帳號, str姓名, str狀態, str建立日期, arr權限 }
 *   obj可指派   {Object} 「取得可指派權限清單」的結果
 * 傳回：{string} HTML
 * ============================================================================
 */
function 產生承辦人HTML(obj人員, obj可指派) {
  const str帳號 = 跳脫HTML(obj人員.str帳號);
  const bool啟用 = obj人員.str狀態 === '啟用';
  const bool展開 = obj頁面狀態.obj展開.人員 === obj人員.str帳號;
  const arr權限 = obj人員.arr權限 || [];

  // 權限分成「目前可指派的」與「已關閉功能、保留中的」
  const arr有效 = arr權限.filter(function (str) { return obj可指派[str]; });
  const int保留 = arr權限.length - arr有效.length;
  const str權限摘要 = arr有效.length === 0
    ? '尚未指派權限'
    : arr有效.map(function (str) { return `${obj可指派[str].str模組名稱}－${obj可指派[str].str項目}`; }).join('、');

  // 權限勾選：依模組分組
  const str勾選 = obj頁面狀態.arr權限選項.length === 0
    ? '<p class="空白提示">尚未開通任何功能。請先到「功能開通」開通，再回來指派。</p>'
    : obj頁面狀態.arr權限選項.map(function (obj模組) {
      const str項目 = obj模組.arr可指派權限.length === 0
        ? '<p class="小字">此功能沒有需要指派的權限。</p>'
        : obj模組.arr可指派權限.map(function (obj權限) {
          const bool已勾 = arr權限.indexOf(obj權限.str權限項目) !== -1;
          return `<label class="權限項">
            <input type="checkbox" name="arr權限" value="${跳脫HTML(obj權限.str權限項目)}"${bool已勾 ? ' checked' : ''}>
            <span>${跳脫HTML(obj權限.str項目)}</span>
            ${obj權限.str說明 ? `<span class="小字">${跳脫HTML(obj權限.str說明)}</span>` : ''}
          </label>`;
        }).join('');
      return `<fieldset class="權限組"><legend>${跳脫HTML(obj模組.str模組名稱)}</legend>${str項目}</fieldset>`;
    }).join('');

  return `<li class="${bool啟用 ? '' : '已停用'}">
    <details class="項目" data-帳號="${str帳號}"${bool展開 ? ' open' : ''}>
      <summary class="項目列">
        <span><span class="項目名稱">${跳脫HTML(obj人員.str姓名)}</span>${bool啟用 ? '' : 狀態標HTML('已停用', '停用')}</span>
        <span class="項目附註">${str帳號}　${跳脫HTML(str權限摘要)}${int保留 > 0 ? `（另有已關閉功能的權限 ${int保留} 項保留中）` : ''}</span>
      </summary>
      <div class="項目內容">
        <h4>基本資料</h4>
        <form class="列表單" data-表單="修改人員" data-帳號="${str帳號}" novalidate>
          <label class="欄位">姓名
            <input class="輸入" name="str姓名" maxlength="30" value="${跳脫HTML(obj人員.str姓名)}" required>
          </label>
          <button type="submit" class="按鈕">儲存姓名</button>
          <button type="button" class="按鈕${bool啟用 ? ' 警示' : ''}" data-動作="${bool啟用 ? '停用人員' : '啟用人員'}"
                  data-帳號="${str帳號}">${bool啟用 ? '停用此承辦人' : '重新啟用'}</button>
        </form>
        <p class="小字">建立於 ${跳脫HTML(obj人員.str建立日期 || '—')}${bool啟用 ? '' : '。停用期間無法登入，權限會保留。'}</p>

        <h4>功能權限</h4>
        <form data-表單="設定權限" data-帳號="${str帳號}" novalidate>
          ${str勾選}
          ${obj頁面狀態.arr權限選項.length === 0 ? '' : '<button type="submit" class="按鈕 主要">儲存權限</button> <span class="小字">　最晚 10 分鐘內生效</span>'}
        </form>
      </div>
    </details>
  </li>`;
}


