/* global obj平台設定, 呼叫平台, 平台前端錯誤, google */
/* exported 取得網址精舍代號, 讀取工作階段代碼, 清除工作階段代碼,
            顯示Google登入按鈕, 取得我的資訊, 登出平台 */


// 瀏覽器不允許保存時（例如無痕模式限制），改存在記憶體，關掉分頁即失效
const obj記憶體保存_ = {};


/**
 * ============================================================================
 * 函式名稱：取得網址精舍代號
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：讀取網址上的 ?site=，統一轉大寫。總管理頁沒有這個參數，傳回空字串。
 * 參數：無
 * 傳回：{string} 精舍代號（大寫）或空字串
 * ============================================================================
 */
function 取得網址精舍代號() {
  const str代號 = new URLSearchParams(window.location.search).get('site') || '';
  return str代號.trim().toUpperCase();
}


/**
 * ============================================================================
 * 函式名稱：取得保存鍵名_（內部使用）
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：每個精舍各用一個鍵名，總管理用 ADMIN。
 * 參數：無
 * 傳回：{string}
 * ============================================================================
 */
function 取得保存鍵名_() {
  return `平台工作階段_${取得網址精舍代號() || 'ADMIN'}`;
}


/**
 * ============================================================================
 * 函式名稱：讀取工作階段代碼
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：取出登入後保存的工作階段代碼。
 * 參數：無
 * 傳回：{string|null}
 * ============================================================================
 */
function 讀取工作階段代碼() {
  const str鍵 = 取得保存鍵名_();
  try {
    return window.localStorage.getItem(str鍵) || obj記憶體保存_[str鍵] || null;
  } catch (err) {
    return obj記憶體保存_[str鍵] || null;
  }
}


/**
 * ============================================================================
 * 函式名稱：保存工作階段代碼_（內部使用）
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：登入成功後保存代碼；瀏覽器不允許時改存在記憶體。
 * 參數：
 *   str代碼   {string} 工作階段代碼
 * 傳回：無
 * ============================================================================
 */
function 保存工作階段代碼_(str代碼) {
  const str鍵 = 取得保存鍵名_();
  obj記憶體保存_[str鍵] = str代碼;
  try {
    window.localStorage.setItem(str鍵, str代碼);
  } catch (err) {
    // 無法保存到瀏覽器：已存在記憶體，本分頁仍可使用
  }
}


/**
 * ============================================================================
 * 函式名稱：清除工作階段代碼
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：登出或登入逾時時清除保存的代碼。
 * 參數：無
 * 傳回：無
 * ============================================================================
 */
function 清除工作階段代碼() {
  const str鍵 = 取得保存鍵名_();
  delete obj記憶體保存_[str鍵];
  try {
    window.localStorage.removeItem(str鍵);
  } catch (err) {
    // 略過
  }
}


/**
 * ============================================================================
 * 函式名稱：等待Google登入元件_（內部使用）
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：Google 登入元件是非同步載入的，最多等 10 秒。
 * 參數：無
 * 傳回：{Promise<void>}
 * ============================================================================
 */
function 等待Google登入元件_() {
  return new Promise(function (fn完成, fn失敗) {
    const int開始 = Date.now();
    (function 檢查() {
      if (window.google && google.accounts && google.accounts.id) return fn完成();
      if (Date.now() - int開始 > 10000) {
        return fn失敗(new 平台前端錯誤('CLIENT_GSI', '無法載入 Google 登入，請確認網路，或關閉擋廣告的外掛後重新整理。'));
      }
      setTimeout(檢查, 100);
    })();
  });
}


/**
 * ============================================================================
 * 函式名稱：顯示Google登入按鈕
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：
 *   在指定位置畫出 Google 登入按鈕。使用者登入 Google 後，自動向後端登入，
 *   成功就保存工作階段代碼並呼叫 fn成功；失敗就呼叫 fn失敗。
 *
 * 參數：
 *   el按鈕位置   {HTMLElement} 放按鈕的元素
 *   fn成功       {Function}    收到 (obj登入結果) — 後端「驗證.Google登入」的回應
 *   fn失敗       {Function}    收到 (平台前端錯誤)
 *   fn處理中     {Function}    選填，送出到後端前呼叫（可顯示「登入中」）
 *
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 顯示Google登入按鈕(el按鈕位置, fn成功, fn失敗, fn處理中) {
  try {
    await 等待Google登入元件_();
  } catch (err) {
    fn失敗(err);
    return;
  }

  // 設定登入完成後要做的事
  google.accounts.id.initialize({
    client_id: obj平台設定.strOAuth用戶端ID,
    callback: async function (obj憑證回應) {
      try {
        if (typeof fn處理中 === 'function') fn處理中();
        const obj結果 = await 呼叫平台('驗證.Google登入', {
          str憑證: obj憑證回應.credential,
          str精舍代號: 取得網址精舍代號()
        }, { bool不帶工作階段: true });
        保存工作階段代碼_(obj結果.str工作階段代碼);
        fn成功(obj結果);
      } catch (err) {
        fn失敗(err instanceof 平台前端錯誤 ? err : new 平台前端錯誤('CLIENT_UNKNOWN', '登入時發生問題，請再試一次。'));
      }
    },
    auto_select: false,
    cancel_on_tap_outside: true
  });

  // 畫出按鈕
  el按鈕位置.innerHTML = '';
  google.accounts.id.renderButton(el按鈕位置, {
    type: 'standard', theme: 'outline', size: 'large', text: 'signin_with',
    shape: 'rectangular', logo_alignment: 'left', locale: 'zh-TW', width: 280
  });
}


/**
 * ============================================================================
 * 函式名稱：取得我的資訊
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：用保存的代碼向後端確認身分；沒有代碼時傳回 null（代表要登入）。
 * 參數：無
 * 傳回：{Promise<Object|null>} 後端「驗證.我的資訊」的回應
 * ============================================================================
 */
async function 取得我的資訊() {
  if (!讀取工作階段代碼()) return null;
  return 呼叫平台('驗證.我的資訊');
}


/**
 * ============================================================================
 * 函式名稱：登出平台
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：通知後端結束工作階段，並清除本機保存；後端失敗也照樣清除本機。
 * 參數：無
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 登出平台() {
  try {
    if (讀取工作階段代碼()) await 呼叫平台('驗證.登出');
  } catch (err) {
    // 後端失敗不影響登出
  } finally {
    清除工作階段代碼();
    // 避免 Google 下次自動帶入同一個帳號
    try { google.accounts.id.disableAutoSelect(); } catch (err) { /* 略過 */ }
  }
}
