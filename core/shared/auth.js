//     · 從網址讀取精舍代號（?site=TC）
//     · 保存工作階段代碼（每個精舍分開保存，同一台電腦可登入不同精舍）
//     · 顯示 Google 登入按鈕，取得身分憑證後向後端登入
//     · 取得我的資訊、登出
