/* exported 平台前端錯誤, 呼叫平台, 設定登入逾時處理 */


/**
 * ============================================================================
 * 類別名稱：平台前端錯誤
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：前端統一的錯誤類型，帶有錯誤代碼與可直接顯示給使用者的訊息。
 * 建構參數：
 *   str錯誤代碼   {string} 與後端相同的代碼（例如 SESSION_EXPIRED），前端自訂的以 CLIENT_ 開頭
 *   str訊息       {string} 白話訊息
 * ============================================================================
 */
class 平台前端錯誤 extends Error {
  constructor(str錯誤代碼, str訊息) {
    super(str訊息);
    this.name = '平台前端錯誤';
    this.str錯誤代碼 = str錯誤代碼;
    this.str訊息 = str訊息;
  }
}


// 收到「登入逾時」時要執行的動作（由頁面設定，例如切回登入畫面）
let fn登入逾時處理_ = null;


/**
 * ============================================================================
 * 函式名稱：設定登入逾時處理
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：頁面登記「登入逾時時要做什麼」，例如顯示登入按鈕。
 * 參數：
 *   fn處理   {Function} 收到 (str訊息) 的函式
 * 傳回：無
 * ============================================================================
 */
function 設定登入逾時處理(fn處理) {
  fn登入逾時處理_ = (typeof fn處理 === 'function') ? fn處理 : null;
}


/**
 * ============================================================================
 * 函式名稱：取得後端網址_（內部使用）
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：依 action 的分類（點號前的部分）決定送往哪個後端。
 * 參數：
 *   str動作   {string} 例如 'event.列出活動'
 * 傳回：{string} 網址
 * ============================================================================
 */
function 取得後端網址_(str動作) {
  const str分類 = String(str動作).split('.')[0];
  return obj平台設定.obj模組後端網址[str分類] || obj平台設定.str預設後端網址;
}


/**
 * ============================================================================
 * 函式名稱：呼叫平台
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：
 *   送出一個 action 到後端並取回結果。成功時傳回後端的資料物件；
 *   失敗時丟出「平台前端錯誤」，頁面只要顯示 err.str訊息 即可。
 *
 * 參數：
 *   str動作         {string}  例如 '驗證.我的資訊'
 *   obj參數         {Object}  選填，傳給後端的參數
 *   obj選項         {Object}  選填，{ bool不帶工作階段: true }（登入前使用）
 *
 * 傳回：{Promise<Object>} 後端回應（bool成功 為 true）
 *
 * 範例：
 *   const obj結果 = await 呼叫平台('精舍.列出人員');
 *   obj結果.arr人員.forEach(…);
 * ============================================================================
 */
async function 呼叫平台(str動作, obj參數, obj選項) {
  const obj設定 = obj選項 || {};

  // 組成請求：工作階段代碼由這裡自動帶上
  const obj請求 = {
    action: str動作,
    token: obj設定.bool不帶工作階段 ? '' : (讀取工作階段代碼() || ''),
    參數: obj參數 || {}
  };

  // 逾時控制：時間到就中止請求
  const obj中止 = new AbortController();
  const int計時 = setTimeout(function () { obj中止.abort(); }, obj平台設定.int請求逾時毫秒);

  let obj回應;
  try {
    // 以 text/plain 送出，避開瀏覽器的跨網域預檢（GAS 不支援預檢）
    const obj網路回應 = await fetch(取得後端網址_(str動作), {
      method: 'POST',
      headers: { 'Content-Type': 'text/plain;charset=utf-8' },
      body: JSON.stringify(obj請求),
      signal: obj中止.signal,
      redirect: 'follow'
    });

    if (!obj網路回應.ok) {
      throw new 平台前端錯誤('CLIENT_HTTP', `系統暫時無法回應（代碼 ${obj網路回應.status}），請稍後再試。`);
    }

    try {
      obj回應 = await obj網路回應.json();
    } catch (err) {
      throw new 平台前端錯誤('CLIENT_BAD_RESPONSE', '系統回應的內容無法辨識，請稍後再試；若一直發生，請通知系統管理員。');
    }
  } catch (err) {
    // 已是我們的錯誤就直接往外丟
    if (err instanceof 平台前端錯誤) throw err;
    // 逾時
    if (err && err.name === 'AbortError') {
      throw new 平台前端錯誤('CLIENT_TIMEOUT', '等候太久沒有回應，請確認網路後再試一次。');
    }
    // 斷線或被瀏覽器擋下
    throw new 平台前端錯誤('CLIENT_NETWORK', '無法連線到系統，請確認網路是否正常後再試一次。');
  } finally {
    clearTimeout(int計時);
  }

  // 後端回報失敗
  if (!obj回應 || obj回應.bool成功 !== true) {
    const str代碼 = (obj回應 && obj回應.str錯誤代碼) || 'CLIENT_UNKNOWN';
    const str訊息 = (obj回應 && obj回應.str訊息) || '發生未預期的問題，請稍後再試。';

    // 登入逾時：清掉保存的代碼，通知頁面回到登入畫面
    if (str代碼 === 'SESSION_EXPIRED') {
      清除工作階段代碼();
      if (fn登入逾時處理_) fn登入逾時處理_(str訊息);
    }
    throw new 平台前端錯誤(str代碼, str訊息);
  }

  return obj回應;
}
