// ----------------------------------------------------------------------------
// 本檔常數
// ----------------------------------------------------------------------------

// 預設的四個狀態區塊（頁面上 id 為「區_名稱」）
const arr預設狀態區塊_ = Object.freeze(['載入', '登入', '無權限', '已登入']);

// 與後端 核心_精舍管理.gs 的 reg電子郵件格式 相同
const reg電子郵件格式_ = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

// 登入逾時的錯誤代碼（api.js 遇到時已自動切回登入畫面，本檔不再重複顯示）
const str登入逾時代碼_ = 'SESSION_EXPIRED';


/**
 * ============================================================================
 * 函式名稱：取得元素
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：依 id 取得頁面元素的簡寫。
 * 參數：str編號 {string} 元素 id
 * 傳回：{HTMLElement|null}
 * ============================================================================
 */
function 取得元素(str編號) {
  return document.getElementById(str編號);
}


/**
 * ============================================================================
 * 函式名稱：跳脫HTML
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：
 *   把文字轉成安全的 HTML，避免名稱中的 < > & " ' 被當成標籤
 *   （防止畫面錯亂或被插入惡意程式）。凡是把資料組進 innerHTML 都要先經過這裡。
 * 參數：值 {*} 任意值（null、undefined 視為空字串）
 * 傳回：{string}
 * ============================================================================
 */
function 跳脫HTML(值) {
  return String(值 === null || 值 === undefined ? '' : 值)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}


/**
 * ============================================================================
 * 函式名稱：切換狀態
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：只顯示指定的狀態區塊，其餘隱藏。
 * 參數：
 *   str狀態     {string}   例如 '載入' | '登入' | '無權限' | '已登入'
 *   arr區塊     {string[]} 選填，頁面有其他狀態區塊時傳入；預設為上述四個
 * 傳回：無
 * ============================================================================
 */
function 切換狀態(str狀態, arr區塊) {
  (arr區塊 || arr預設狀態區塊_).forEach(function (str名稱) {
    const el區塊 = 取得元素(`區_${str名稱}`);
    // 頁面缺少某個區塊時略過，並在主控台提醒開發者
    if (!el區塊) { console.warn(`切換狀態：頁面上找不到「區_${str名稱}」`); return; }
    el區塊.hidden = (str名稱 !== str狀態);
  });
}


/**
 * ============================================================================
 * 函式名稱：顯示訊息
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：頁面層級的訊息（登入失敗、載入清單失敗等）。傳空字串則隱藏。
 * 參數：
 *   str訊息   {string}
 *   bool一般  {boolean} 選填，true 為一般提醒（綠框）；預設為錯誤樣式（紅框）
 * 傳回：無
 * ============================================================================
 */
function 顯示訊息(str訊息, bool一般) {
  const el訊息 = 取得元素('訊息');
  if (!el訊息) { console.warn('顯示訊息：頁面上找不到 id="訊息" 的元素'); return; }
  el訊息.textContent = str訊息 || '';
  el訊息.hidden = !str訊息;
  el訊息.classList.toggle('一般', Boolean(bool一般));
  // 錯誤用 alert 讓螢幕報讀立即念出；一般提醒用 status
  el訊息.setAttribute('role', bool一般 ? 'status' : 'alert');
}


/**
 * ============================================================================
 * 函式名稱：顯示區塊訊息
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：
 *   把訊息顯示在某個區塊（例如展開的精舍、展開的承辦人）的最上方，
 *   不重畫區塊，已輸入的內容會保留。區塊內已有訊息就直接替換。
 * 參數：
 *   el容器    {HTMLElement} 要顯示訊息的區塊；傳 null 則不做事
 *   str訊息   {string}      傳空字串則移除訊息
 *   bool一般  {boolean}     選填，true 為一般提醒
 * 傳回：無
 * ============================================================================
 */
function 顯示區塊訊息(el容器, str訊息, bool一般) {
  if (!el容器) return;
  let el訊息 = el容器.querySelector(':scope > .訊息');

  // 清除訊息
  if (!str訊息) { if (el訊息) el訊息.remove(); return; }

  // 沒有就新建，放在區塊最上方
  if (!el訊息) {
    el訊息 = document.createElement('p');
    el容器.prepend(el訊息);
  }
  el訊息.className = '訊息' + (bool一般 ? ' 一般' : '');
  el訊息.setAttribute('role', bool一般 ? 'status' : 'alert');
  el訊息.textContent = str訊息;
}


/**
 * ============================================================================
 * 函式名稱：取得錯誤訊息
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：
 *   從錯誤物件取出要顯示的文字。api.js 的錯誤都帶有後端給的白話 str訊息；
 *   其他未預期的錯誤（程式寫錯等）印到主控台，畫面只顯示一般說明。
 * 參數：err {Error}
 * 傳回：{string}
 * ============================================================================
 */
function 取得錯誤訊息(err) {
  if (err && err.str訊息) return err.str訊息;
  console.error(err);
  return '頁面發生未預期的問題，請重新整理後再試。';
}


/**
 * ============================================================================
 * 函式名稱：執行操作
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：
 *   所有「按按鈕 → 呼叫後端」的共用包裝：
 *     1. 按鈕改為「處理中…」並停用，防止重複送出
 *     2. 執行 fn工作
 *     3. 失敗時把白話訊息交給 fn顯示錯誤；
 *        登入逾時不處理（api.js 已切回登入畫面）
 *     4. 無論成敗都還原按鈕（按鈕若已因重畫而移除就略過）
 * 參數：
 *   el按鈕       {HTMLElement|null} 觸發的按鈕；沒有按鈕傳 null
 *   fn工作       {Function}         async 函式
 *   fn顯示錯誤   {Function}         收到 (str訊息)
 * 傳回：{Promise<*>} 成功時為 fn工作 的結果；失敗為 undefined
 * ============================================================================
 */
async function 執行操作(el按鈕, fn工作, fn顯示錯誤) {
  const str原文字 = el按鈕 ? el按鈕.textContent : '';
  if (el按鈕) { el按鈕.disabled = true; el按鈕.textContent = '處理中…'; }
  try {
    return await fn工作();
  } catch (err) {
    if (!(err && err.str錯誤代碼 === str登入逾時代碼_)) {
      // 呼叫端忘了給顯示方式時，退回頁面層級訊息，錯誤不會被吞掉
      (typeof fn顯示錯誤 === 'function' ? fn顯示錯誤 : 顯示訊息)(取得錯誤訊息(err));
    }
    return undefined;
  } finally {
    // 按鈕可能已因重畫而移除；仍在頁面上才還原
    if (el按鈕 && el按鈕.isConnected) { el按鈕.disabled = false; el按鈕.textContent = str原文字; }
  }
}


/**
 * ============================================================================
 * 函式名稱：檢查電子郵件格式
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：與後端 reg電子郵件格式 相同的格式檢查（後端仍會再檢查一次）。
 * 參數：str帳號 {string}
 * 傳回：{boolean}
 * ============================================================================
 */
function 檢查電子郵件格式(str帳號) {
  return reg電子郵件格式_.test(String(str帳號 || '').trim());
}


/**
 * ============================================================================
 * 函式名稱：標記欄位
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：把欄位標成錯誤（紅框）並移入焦點，傳回訊息方便一行寫完：
 *         return 顯示區塊訊息(el, 標記欄位(el姓名, '請填寫姓名。'));
 * 參數：
 *   el欄位   {HTMLInputElement}
 *   str訊息  {string}
 * 傳回：{string} str訊息
 * ============================================================================
 */
function 標記欄位(el欄位, str訊息) {
  if (el欄位) {
    el欄位.setAttribute('aria-invalid', 'true');
    el欄位.focus();
  }
  return str訊息;
}


/**
 * ============================================================================
 * 函式名稱：清除欄位錯誤
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：清除範圍內所有欄位的錯誤標記。
 * 參數：el範圍 {HTMLElement} 表單或區塊
 * 傳回：無
 * ============================================================================
 */
function 清除欄位錯誤(el範圍) {
  if (!el範圍) return;
  el範圍.querySelectorAll('[aria-invalid]').forEach(function (el) { el.removeAttribute('aria-invalid'); });
}
