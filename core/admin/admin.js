/**
 * ============================================================================
 * 函式名稱：檢查開通表單
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：送出前在瀏覽器檢查（後端也會再檢查）。四個欄位都是必填（後端規定第一位管理員必填）。
 * 參數：el表單 {HTMLFormElement}
 * 傳回：{string} 錯誤訊息；沒有錯誤為空字串
 * ============================================================================
 */
function 檢查開通表單(el表單) {
  const obj欄 = el表單.elements;
  清除欄位錯誤(el表單);

  const str代號 = obj欄.str精舍代號.value.trim().toUpperCase();
  if (!str代號) return 標記欄位(obj欄.str精舍代號, '請填寫精舍代號。');
  if (!/^[A-Z0-9]+$/.test(str代號)) return 標記欄位(obj欄.str精舍代號, '精舍代號只能使用英文字母或數字。');
  const obj重複 = 找出精舍(str代號);
  if (obj重複) return 標記欄位(obj欄.str精舍代號, `精舍代號「${str代號}」已被「${obj重複.str精舍名稱}」使用，請換一個代號。`);
  if (!obj欄.str精舍名稱.value.trim()) return 標記欄位(obj欄.str精舍名稱, '請填寫精舍名稱。');
  if (!檢查電子郵件格式(obj欄.str管理員帳號.value.trim())) {
    return 標記欄位(obj欄.str管理員帳號, '請填寫第一位精舍管理員的 Google 帳號，格式類似 name@gmail.com。');
  }
  if (!obj欄.str管理員姓名.value.trim()) return 標記欄位(obj欄.str管理員姓名, '請填寫管理員姓名。');
  return '';
}


/**
 * ============================================================================
 * 函式名稱：送出開通精舍
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：呼叫「系統.開通精舍」。成功後關閉對話框、重新載入清單並展開新精舍。
 *       建立資料夾與試算表需數秒至數十秒，按鈕會顯示處理中。
 * 參數：e {SubmitEvent}
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 送出開通精舍(e) {
  e.preventDefault();
  const el表單 = 取得元素('開通表單');
  const el錯誤 = 取得元素('開通錯誤');
  el錯誤.textContent = '';
  const str檢查 = 檢查開通表單(el表單);
  if (str檢查) { el錯誤.textContent = str檢查; return; }

  const obj欄 = el表單.elements;
  const obj參數 = {
    str精舍代號: obj欄.str精舍代號.value.trim().toUpperCase(),
    str精舍名稱: obj欄.str精舍名稱.value.trim(),
    str管理員帳號: obj欄.str管理員帳號.value.trim().toLowerCase(),
    str管理員姓名: obj欄.str管理員姓名.value.trim()
  };

  // 開通期間停用取消鈕，避免使用者以為已取消而重複開通
  取得元素('開通取消').disabled = true;
  const obj結果 = await 執行操作(取得元素('開通送出'), function () {
    return 呼叫平台('系統.開通精舍', obj參數);
  }, function (str訊息) {
    el錯誤.textContent = str訊息;
  });
  取得元素('開通取消').disabled = false;
  if (!obj結果) return;

  取得元素('開通對話框').close();
  obj頁面狀態.str搜尋 = '';
  取得元素('搜尋欄').value = '';
  obj頁面狀態.str展開代號 = obj結果.str精舍代號 || obj參數.str精舍代號;
  obj頁面狀態.obj列訊息 = { str代號: obj頁面狀態.str展開代號, str訊息: obj結果.str訊息 || '已開通。', bool一般: true };
  await 執行操作(null, 載入精舍清單, 顯示訊息);

  // 捲到新精舍
  const el新列 = 取得元素('精舍清單').querySelector(`details[data-代號="${CSS.escape(obj頁面狀態.str展開代號)}"]`);
  if (el新列) el新列.scrollIntoView({ block: 'start', behavior: 'smooth' });
}


