// 頁面狀態：畫面一律依此重畫
const obj頁面狀態 = {
  arr精舍: [],          // 後端「系統.列出精舍」的 arr精舍
  str搜尋: '',          // 搜尋欄文字
  str展開代號: '',      // 目前展開的精舍（重新載入後保持展開）
  obj列訊息: null       // { str代號, str訊息, bool一般 }：顯示在展開精舍內的操作結果
};

// 頁面上四個狀態區塊
const arr區塊名稱 = ['載入', '登入', '無權限', '已登入'];


/**
 * ============================================================================
 * 函式名稱：取得元素
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：依 id 取得頁面元素的簡寫。
 * 參數：str編號 {string} 元素 id
 * 傳回：{HTMLElement}
 * ============================================================================
 */
function 取得元素(str編號) {
  return document.getElementById(str編號);
}


/**
 * ============================================================================
 * 函式名稱：跳脫HTML
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：把文字轉成安全的 HTML，避免精舍名稱中的符號被當成標籤（防止畫面錯亂或注入）。
 * 參數：值 {*} 任意值
 * 傳回：{string}
 * ============================================================================
 */
function 跳脫HTML(值) {
  return String(值 === null || 值 === undefined ? '' : 值)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}


/**
 * ============================================================================
 * 函式名稱：切換狀態
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：只顯示指定的狀態區塊。
 * 參數：str狀態 {string} '載入' | '登入' | '無權限' | '已登入'
 * 傳回：無
 * ============================================================================
 */
function 切換狀態(str狀態) {
  arr區塊名稱.forEach(function (str名稱) {
    取得元素(`區_${str名稱}`).hidden = (str名稱 !== str狀態);
  });
}


/**
 * ============================================================================
 * 函式名稱：顯示訊息
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：頁面層級的訊息（登入、載入清單失敗等）。傳空字串則隱藏。
 * 參數：
 *   str訊息   {string}
 *   bool一般  {boolean} 選填，true 為一般提醒，預設為錯誤樣式
 * 傳回：無
 * ============================================================================
 */
function 顯示訊息(str訊息, bool一般) {
  const el訊息 = 取得元素('訊息');
  el訊息.textContent = str訊息 || '';
  el訊息.hidden = !str訊息;
  el訊息.classList.toggle('一般', Boolean(bool一般));
  el訊息.setAttribute('role', bool一般 ? 'status' : 'alert');
}


/**
 * ============================================================================
 * 函式名稱：取得錯誤訊息
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：從錯誤物件取出要顯示的文字。共用 api.js 的錯誤都有 str訊息。
 * 參數：err {Error}
 * 傳回：{string}
 * ============================================================================
 */
function 取得錯誤訊息(err) {
  if (err && err.str訊息) return err.str訊息;
  console.error(err);
  return '頁面發生未預期的問題，請重新整理後再試。';
}


/**
 * ============================================================================
 * 函式名稱：執行操作
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：
 *   所有「按按鈕 → 呼叫後端」的共用包裝：
 *     1. 按鈕改為「處理中…」並停用，防止重複送出
 *     2. 執行 fn工作
 *     3. 失敗時把訊息交給 fn顯示錯誤；登入逾時則不處理（共用模組會切回登入畫面）
 * 參數：
 *   el按鈕       {HTMLElement|null} 觸發的按鈕
 *   fn工作       {Function}         async 函式
 *   fn顯示錯誤   {Function}         收到 (str訊息)
 * 傳回：{Promise<*>} 成功時為 fn工作 的結果；失敗為 undefined
 * ============================================================================
 */
async function 執行操作(el按鈕, fn工作, fn顯示錯誤) {
  const str原文字 = el按鈕 ? el按鈕.textContent : '';
  if (el按鈕) { el按鈕.disabled = true; el按鈕.textContent = '處理中…'; }
  try {
    return await fn工作();
  } catch (err) {
    if (!(err && err.str錯誤代碼 === 'SESSION_EXPIRED')) fn顯示錯誤(取得錯誤訊息(err));
    return undefined;
  } finally {
    // 按鈕可能已因重畫而移除；仍在頁面上才還原
    if (el按鈕 && el按鈕.isConnected) { el按鈕.disabled = false; el按鈕.textContent = str原文字; }
  }
}


