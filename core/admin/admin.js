/**
 * ============================================================================
 * 函式名稱：載入精舍清單
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：呼叫「系統.列出精舍」並重畫清單。失敗時丟出錯誤，由呼叫端處理。
 * 參數：無
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 載入精舍清單() {
  const obj結果 = await 呼叫平台('系統.列出精舍');
  obj頁面狀態.arr精舍 = Array.isArray(obj結果.arr精舍) ? obj結果.arr精舍 : [];
  // 依代號排序，方便查找
  obj頁面狀態.arr精舍.sort(function (a, b) { return a.str精舍代號.localeCompare(b.str精舍代號); });
  顯示訊息('');
  畫精舍清單();
}


/**
 * ============================================================================
 * 函式名稱：找出精舍
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：從目前清單依代號取出精舍。
 * 參數：str代號 {string}
 * 傳回：{Object|null}
 * ============================================================================
 */
function 找出精舍(str代號) {
  return obj頁面狀態.arr精舍.find(function (obj) { return obj.str精舍代號 === str代號; }) || null;
}


/**
 * ============================================================================
 * 函式名稱：取得啟用管理員
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：取出精舍中狀態為「啟用」的管理員。
 * 參數：obj精舍 {Object}
 * 傳回：{Object[]}
 * ============================================================================
 */
function 取得啟用管理員(obj精舍) {
  return (obj精舍.arr管理員 || []).filter(function (obj) { return obj.str狀態 === '啟用'; });
}


/**
 * ============================================================================
 * 函式名稱：畫精舍清單
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：依搜尋文字篩選後畫出清單與統計。每個精舍是一個可展開的 <details>，
 *       展開的那一個在重畫後保持展開。
 * 參數：無
 * 傳回：無
 * ============================================================================
 */
function 畫精舍清單() {
  const str關鍵字 = obj頁面狀態.str搜尋.trim().toUpperCase();
  const arr全部 = obj頁面狀態.arr精舍;
  const arr顯示 = arr全部.filter(function (obj) {
    return !str關鍵字
      || obj.str精舍代號.toUpperCase().indexOf(str關鍵字) !== -1
      || String(obj.str精舍名稱).toUpperCase().indexOf(str關鍵字) !== -1;
  });

  // 統計
  const int啟用 = arr全部.filter(function (obj) { return obj.str狀態 === '啟用'; }).length;
  取得元素('統計').textContent = `共 ${arr全部.length} 個精舍，啟用中 ${int啟用} 個`
    + (str關鍵字 ? `；符合搜尋 ${arr顯示.length} 個` : '');

  // 空清單
  const el清單 = 取得元素('精舍清單');
  if (arr顯示.length === 0) {
    el清單.innerHTML = `<li class="空白提示">${arr全部.length === 0
      ? '還沒有開通任何精舍。按「開通精舍」新增第一個。'
      : '找不到符合的精舍，換個關鍵字試試。'}</li>`;
    return;
  }

  el清單.innerHTML = arr顯示.map(產生精舍列HTML).join('');
}


/**
 * ============================================================================
 * 函式名稱：產生精舍列HTML
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：產生一個精舍的清單列，含展開後的管理內容：
 *         · 精舍名稱修改、停用／重新啟用精舍
 *         · 精舍管理員清單（停用／重新啟用）
 *         · 新增精舍管理員
 * 參數：obj精舍 {Object} { str精舍代號, str精舍名稱, str狀態, str開通日期, arr管理員 }
 * 傳回：{string} HTML
 * ============================================================================
 */
function 產生精舍列HTML(obj精舍) {
  const str代號 = 跳脫HTML(obj精舍.str精舍代號);
  const bool啟用 = obj精舍.str狀態 === '啟用';
  const arr啟用管理員 = 取得啟用管理員(obj精舍);
  const bool展開 = obj精舍.str精舍代號 === obj頁面狀態.str展開代號;

  // 摘要列的附註：管理員姓名或提醒
  const str附註 = arr啟用管理員.length > 0
    ? `管理員：${arr啟用管理員.map(function (obj) { return obj.str姓名; }).join('、')}`
    : '沒有啟用中的管理員';

  // 管理員清單：停用按鈕只在「啟用中且不是最後一位」時出現（後端也會擋）
  const arr管理員 = (obj精舍.arr管理員 || []).slice().sort(function (a, b) {
    return (a.str狀態 === '啟用' ? 0 : 1) - (b.str狀態 === '啟用' ? 0 : 1);
  });
  const str管理員清單 = arr管理員.length === 0
    ? '<li class="空白提示">尚未登記管理員。</li>'
    : arr管理員.map(function (obj) {
      const bool管理員啟用 = obj.str狀態 === '啟用';
      let str按鈕 = '';
      if (!bool管理員啟用) {
        str按鈕 = `<button type="button" class="按鈕 小" data-動作="啟用管理員" data-代號="${str代號}"
                    data-帳號="${跳脫HTML(obj.str帳號)}" data-姓名="${跳脫HTML(obj.str姓名)}">重新啟用</button>`;
      } else if (arr啟用管理員.length > 1) {
        str按鈕 = `<button type="button" class="按鈕 小 警示" data-動作="停用管理員" data-代號="${str代號}"
                    data-帳號="${跳脫HTML(obj.str帳號)}" data-姓名="${跳脫HTML(obj.str姓名)}">停用</button>`;
      } else {
        str按鈕 = '<span class="小字">唯一的管理員，需先新增他人才能停用</span>';
      }
      return `<li class="${bool管理員啟用 ? '' : '停用'}">
          <span><span class="姓名">${跳脫HTML(obj.str姓名)}</span>${bool管理員啟用 ? '' : '<span class="小字">（已停用）</span>'}<br>
                <span class="帳號">${跳脫HTML(obj.str帳號)}</span></span>
          ${str按鈕}
        </li>`;
    }).join('');

  // 操作結果訊息（只顯示在剛操作的精舍）
  const obj訊息 = obj頁面狀態.obj列訊息;
  const str訊息 = (obj訊息 && obj訊息.str代號 === obj精舍.str精舍代號)
    ? `<p class="訊息${obj訊息.bool一般 ? ' 一般' : ''}" role="${obj訊息.bool一般 ? 'status' : 'alert'}">${跳脫HTML(obj訊息.str訊息)}</p>`
    : '';

  return `<li class="${bool啟用 ? '' : '已停用'}">
    <details data-代號="${str代號}"${bool展開 ? ' open' : ''}>
      <summary>
        <span class="精舍代號">${str代號}</span>
        <span class="精舍名稱">${跳脫HTML(obj精舍.str精舍名稱)}</span>
        <span class="狀態字">${bool啟用 ? '' : '已停用'}</span>
        <span class="精舍附註">${跳脫HTML(str附註)}　開通於 ${跳脫HTML(obj精舍.str開通日期 || '—')}</span>
      </summary>
      <div class="管理內容">
        ${str訊息}
        <h3>精舍資料</h3>
        <form class="列表單" data-表單="改名" data-代號="${str代號}" novalidate>
          <label class="欄位">精舍名稱
            <input class="輸入" name="str精舍名稱" maxlength="40" value="${跳脫HTML(obj精舍.str精舍名稱)}" required>
          </label>
          <button type="submit" class="按鈕">儲存名稱</button>
          <button type="button" class="按鈕${bool啟用 ? ' 警示' : ''}" data-動作="${bool啟用 ? '停用精舍' : '啟用精舍'}"
                  data-代號="${str代號}">${bool啟用 ? '停用此精舍' : '重新啟用此精舍'}</button>
        </form>

        <h3>精舍管理員</h3>
        <ul class="管理員清單">${str管理員清單}</ul>

        <h3>新增精舍管理員</h3>
        <form class="列表單" data-表單="新增管理員" data-代號="${str代號}" novalidate>
          <label class="欄位">Google 帳號
            <input class="輸入" name="str帳號" type="email" maxlength="120" autocomplete="off" placeholder="name@gmail.com" required>
          </label>
          <label class="欄位">姓名
            <input class="輸入" name="str姓名" maxlength="30" required>
          </label>
          <button type="submit" class="按鈕">新增管理員</button>
        </form>
      </div>
    </details>
  </li>`;
}


