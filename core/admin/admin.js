/**
 * ============================================================================
 * 函式名稱：啟動總管理頁
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：開頁時綁定事件，用保存的工作階段確認身分；沒有或逾時就顯示登入。
 * 參數：無
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 啟動總管理頁() {
  // 任何請求遇到登入逾時，都回到登入畫面
  設定登入逾時處理(function (str訊息) {
    if (取得元素('開通對話框').open) 取得元素('開通對話框').close();
    顯示登入(str訊息);
  });
  綁定事件();

  切換狀態('載入');
  try {
    const obj資訊 = await 取得我的資訊();
    if (obj資訊) {
      await 進入總管理(obj資訊);
    } else {
      顯示登入();
    }
  } catch (err) {
    // 登入逾時已由處理函式切回登入畫面
    if (err.str錯誤代碼 !== 'SESSION_EXPIRED') 顯示登入(取得錯誤訊息(err));
  }
}


/**
 * ============================================================================
 * 函式名稱：顯示登入
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：切到登入畫面並畫出 Google 登入按鈕（使用共用 auth.js）。
 * 參數：
 *   str提醒   {string}  選填，例如「登入已逾時」
 *   bool一般  {boolean} 選填，true 表示不是錯誤（例如「已登出」）
 * 傳回：無
 * ============================================================================
 */
function 顯示登入(str提醒, bool一般) {
  取得元素('登入中').hidden = true;
  顯示訊息(str提醒 || '', bool一般);
  切換狀態('登入');

  顯示Google登入按鈕(
    取得元素('google按鈕'),
    function 成功() {
      顯示訊息('');
      // 登入回應只有身分，統一再取一次我的資訊
      取得我的資訊()
        .then(進入總管理)
        .catch(function (err) { 顯示登入(取得錯誤訊息(err)); });
    },
    function 失敗(err) {
      取得元素('登入中').hidden = true;
      顯示訊息(取得錯誤訊息(err));
    },
    function 處理中() {
      顯示訊息('');
      取得元素('登入中').hidden = false;
    }
  );
}


/**
 * ============================================================================
 * 函式名稱：進入總管理
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：確認角色是系統管理員才顯示管理畫面，否則顯示無權限。
 *       （真正的權限由後端每個 系統.* 動作檢查，這裡只決定畫面。）
 * 參數：obj資訊 {Object} 後端「驗證.我的資訊」的回應 { obj身分, arr模組 }
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 進入總管理(obj資訊) {
  const obj身分 = obj資訊.obj身分 || {};
  if (obj身分.str角色 !== '系統管理員') {
    取得元素('無權限帳號').textContent = obj身分.str帳號 || '';
    切換狀態('無權限');
    return;
  }

  取得元素('問候').textContent = `${obj身分.str帳號}，您好`;
  document.title = `總管理｜${obj平台設定.str平台名稱}`;
  切換狀態('已登入');
  取得元素('精舍清單').innerHTML = '<li class="空白提示">正在讀取精舍清單…</li>';

  await 執行操作(null, 載入精舍清單, function (str訊息) {
    取得元素('精舍清單').innerHTML = '';
    顯示訊息(str訊息);
  });
}


/**
 * ============================================================================
 * 函式名稱：執行登出
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：通知後端結束工作階段並清除本機，回到登入畫面。
 * 參數：el按鈕 {HTMLElement} 被按下的按鈕
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 執行登出(el按鈕) {
  el按鈕.disabled = true;
  await 登出平台();     // 共用函式：後端失敗也會清除本機
  el按鈕.disabled = false;
  obj頁面狀態.arr精舍 = [];
  obj頁面狀態.str展開代號 = '';
  obj頁面狀態.obj列訊息 = null;
  顯示登入('已登出。', true);
}


