/**
 * ============================================================================
 * 函式名稱：綁定事件
 * 版本：v1.0.0（2026-10-25）
 * ----------------------------------------------------------------------------
 * 用途：集中綁定所有事件。清單使用事件委派，重畫後不必重綁。
 * 參數：無
 * 傳回：無
 * ============================================================================
 */
function 綁定事件() {
  // 登出／換帳號
  取得元素('登出按鈕').addEventListener('click', function () { 執行登出(this); });
  取得元素('換帳號按鈕').addEventListener('click', function () { 執行登出(this); });

  // 搜尋
  取得元素('搜尋欄').addEventListener('input', function (e) {
    obj頁面狀態.str搜尋 = e.target.value;
    畫精舍清單();
  });

  // 清單：按鈕與表單（事件委派）
  const el清單 = 取得元素('精舍清單');
  el清單.addEventListener('click', 處理清單按鈕);
  el清單.addEventListener('submit', 處理清單表單);
  // 記住展開的精舍；一次只展開一個，切換時清掉舊的操作訊息
  el清單.addEventListener('toggle', function (e) {
    const el展開 = e.target;
    if (!el展開.matches || !el展開.matches('details')) return;
    if (el展開.open) {
      if (obj頁面狀態.str展開代號 !== el展開.dataset.代號) obj頁面狀態.obj列訊息 = null;
      obj頁面狀態.str展開代號 = el展開.dataset.代號;
      el清單.querySelectorAll('details[open]').forEach(function (el) { if (el !== el展開) el.open = false; });
    } else if (obj頁面狀態.str展開代號 === el展開.dataset.代號) {
      obj頁面狀態.str展開代號 = '';
    }
  }, true);   // toggle 不會冒泡，用捕捉階段

  // 開通精舍
  取得元素('開通按鈕').addEventListener('click', 開啟開通對話框);
  取得元素('開通表單').addEventListener('submit', 送出開通精舍);
  取得元素('開通取消').addEventListener('click', function () { 取得元素('開通對話框').close(); });
  // 代號輸入時即轉大寫（與後端儲存方式一致）
  取得元素('開通表單').elements.str精舍代號.addEventListener('input', function (e) {
    const int游標 = e.target.selectionStart;
    e.target.value = e.target.value.toUpperCase();
    e.target.setSelectionRange(int游標, int游標);
  });
  // 開通處理中不允許按 Esc 關閉
  取得元素('開通對話框').addEventListener('cancel', function (e) {
    if (取得元素('開通送出').disabled) e.preventDefault();
  });
}


