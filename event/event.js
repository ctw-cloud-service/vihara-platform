/**
 * ============================================================================
 * 函式名稱：確認對話框
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：顯示確認對話框，等使用者按「確定」或「取消」（按 Esc 視為取消）。
 * 參數：
 *   str標題       {string} 純文字標題
 *   str內容HTML   {string} 內容（呼叫端負責跳脫資料）
 *   str確定文字   {string} 確定按鈕的文字
 * 傳回：{Promise<boolean>} true＝確定
 * ============================================================================
 */
function 確認對話框(str標題, str內容HTML, str確定文字) {
  const el框 = 取得元素('確認框');
  取得元素('確認標題').textContent = str標題;
  取得元素('確認內容').innerHTML = str內容HTML;
  取得元素('確認按鈕').textContent = str確定文字 || '確定';
  el框.returnValue = '';
  return new Promise(function (fn完成) {
    el框.addEventListener('close', function 關閉() {
      el框.removeEventListener('close', 關閉);
      fn完成(el框.returnValue === '確定');
    });
    el框.showModal();
  });
}


