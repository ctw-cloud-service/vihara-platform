/**
 * ============================================================================
 * 函式名稱：處理重複按鈕
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：
 *   查詢重複：顯示各組列號（只讀）
 *   移除重複：先預覽 → 確認對話框列出將移出的列 → 確定才執行，完成後再查一次
 *   重新設定標示：重設淡橘色標示與「重複檢查」分頁
 * 參數：el按鈕 {HTMLElement}
 * 傳回：{Promise<void>}
 * ============================================================================
 */
async function 處理重複按鈕(el按鈕) {
  const str活動ID = obj頁面狀態.str重複活動ID;
  if (!str活動ID) return;
  const fn位置 = function () { return 取得元素('卡片_重複'); };
  const fn查詢 = async function () {
    obj頁面狀態.obj重複結果 = await 呼叫平台('event.查詢重複', { str活動ID: str活動ID });
    畫同步與整理();
  };
  顯示區塊訊息(fn位置(), '');

  switch (el按鈕.dataset.動作) {
    case '查詢重複':
      執行操作(el按鈕, fn查詢, function (str訊息) { 顯示區塊訊息(fn位置(), str訊息); });
      break;

    case '重設標示':
      執行操作(el按鈕, async function () {
        const obj結果 = await 呼叫平台('event.設定重複標示', { str活動ID: str活動ID });
        顯示區塊訊息(fn位置(), obj結果.str訊息, true);
      }, function (str訊息) { 顯示區塊訊息(fn位置(), str訊息); });
      break;

    case '移除重複': {
      // ① 預覽
      const obj預覽 = await 執行操作(el按鈕, function () {
        return 呼叫平台('event.移除重複', { str活動ID: str活動ID, bool僅預覽: true });
      }, function (str訊息) { 顯示區塊訊息(fn位置(), str訊息); });
      if (!obj預覽) return;
      if (!(obj預覽.int移出筆數 > 0)) { 顯示區塊訊息(fn位置(), obj預覽.str訊息, true); return; }

      // ② 確認
      const arr行 = obj預覽.arr明細.slice(0, 20).map(function (o) {
        return `<li>${跳脫HTML(o.str鍵值)}：保留第 ${Number(o.int保留列號)} 列（${跳脫HTML(o.str保留時間)}），移出第 ${o.arr移出列號.map(Number).join('、')} 列</li>`;
      });
      if (obj預覽.arr明細.length > 20) arr行.push(`<li>……另有 ${obj預覽.arr明細.length - 20} 組未列出</li>`);
      const bool確定 = await 確認對話框('移除重複資料？',
        `<p>發現 ${obj預覽.int重複組數} 組姓名重複，將保留每組時間最晚的一筆，其餘 ${obj預覽.int移出筆數} 筆整列移到「無效資料」：</p>
         <ul class="明細">${arr行.join('')}</ul>
         <p class="小字">同名不一定是同一人，請先到副本確認。移出的資料仍在「無效資料」分頁，需要時可複製回來。</p>`, '移除重複');
      if (!bool確定) return;

      // ③ 執行，完成後再查一次
      執行操作(取得元素('卡片_重複').querySelector('[data-動作="移除重複"]'), async function () {
        const obj結果 = await 呼叫平台('event.移除重複', { str活動ID: str活動ID, bool僅預覽: false });
        await fn查詢();
        顯示區塊訊息(fn位置(), obj結果.str訊息, true);
      }, function (str訊息) { 顯示區塊訊息(fn位置(), str訊息); });
      break;
    }

    default:
      break;
  }
}


