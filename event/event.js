/**
 * ============================================================================
 * 函式名稱：切換分頁
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：顯示指定分頁並記在網址 #；第一次顯示時才讀取資料。
 * 參數：
 *   str分頁     {string}
 *   bool移焦點  {boolean} 選填，方向鍵切換時把焦點移到標籤
 * 傳回：無
 * ============================================================================
 */
function 切換分頁(str分頁, bool移焦點) {
  if (arr法會分頁.indexOf(str分頁) === -1) return;
  obj頁面狀態.str目前分頁 = str分頁;
  arr法會分頁.forEach(function (str名稱) {
    const bool選中 = str名稱 === str分頁;
    const el標籤 = 取得元素(`分頁_${str名稱}`);
    el標籤.setAttribute('aria-selected', bool選中 ? 'true' : 'false');
    el標籤.tabIndex = bool選中 ? 0 : -1;
    取得元素(`面板_${str名稱}`).hidden = !bool選中;
  });
  if (bool移焦點) 取得元素(`分頁_${str分頁}`).focus();
  try {
    window.history.replaceState(null, '', `${window.location.pathname}${window.location.search}#${encodeURIComponent(str分頁)}`);
  } catch (err) { /* 少數環境不允許修改網址，略過 */ }
  顯示分頁時載入(str分頁);
}


/**
 * ============================================================================
 * 函式名稱：處理分頁按鍵
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：← → 切換上一個／下一個標籤，Home／End 到頭尾。
 * 參數：e {KeyboardEvent}
 * 傳回：無
 * ============================================================================
 */
function 處理分頁按鍵(e) {
  const int目前 = arr法會分頁.indexOf(obj頁面狀態.str目前分頁);
  const int總數 = arr法會分頁.length;
  let int目標 = -1;
  if (e.key === 'ArrowRight') int目標 = (int目前 + 1) % int總數;
  else if (e.key === 'ArrowLeft') int目標 = (int目前 - 1 + int總數) % int總數;
  else if (e.key === 'Home') int目標 = 0;
  else if (e.key === 'End') int目標 = int總數 - 1;
  if (int目標 === -1) return;
  e.preventDefault();
  切換分頁(arr法會分頁[int目標], true);
}


/**
 * ============================================================================
 * 函式名稱：載入分頁
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：向後端讀取某分頁的資料並重畫；同一分頁讀取中時共用同一次讀取。
 * 參數：str分頁 {string}
 * 傳回：{Promise<void>}
 * ============================================================================
 */
function 載入分頁(str分頁) {
  if (obj頁面狀態.obj載入中[str分頁]) return obj頁面狀態.obj載入中[str分頁];
  const fn載入 = { 活動清單: 載入活動清單, 同步與整理: 載入同步與整理, 大車點名: 載入大車點名 }[str分頁];
  if (!fn載入) return Promise.resolve();
  const obj讀取 = fn載入()
    .then(function () { obj頁面狀態.obj已載入[str分頁] = true; })
    .finally(function () { delete obj頁面狀態.obj載入中[str分頁]; });
  obj頁面狀態.obj載入中[str分頁] = obj讀取;
  return obj讀取;
}


