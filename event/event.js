/**
 * ============================================================================
 * 函式名稱：進入法會活動
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：
 *   確認角色（精舍管理員或承辦人）與精舍已開通法會活動，才顯示活動畫面。
 *   （真正的權限由後端每個動作檢查，這裡只決定畫面。）
 * 參數：obj資訊 {Object} 後端「驗證.我的資訊」的回應 { obj身分, arr模組 }
 * 傳回：無
 * ============================================================================
 */
function 進入法會活動(obj資訊) {
  const obj身分 = obj資訊.obj身分 || {};
  obj頁面狀態.obj身分 = obj身分;
  取得元素('匾額文字').textContent = obj身分.str精舍名稱 || '法會活動';
  document.title = `法會活動｜${obj身分.str精舍名稱 || obj平台設定.str平台名稱}`;
  顯示訊息('');

  // 角色
  if (obj身分.str角色 !== '精舍管理員' && obj身分.str角色 !== '承辦人') {
    顯示無法使用('法會活動只限精舍管理員與承辦人使用',
      `目前登入：${obj身分.str帳號 || ''}（${obj身分.str角色 || ''}）。請從精舍的專屬網址，以精舍人員的帳號登入。`);
    return;
  }
  // 精舍是否開通了法會活動
  const bool已開通 = (obj資訊.arr模組 || []).some(function (o) { return o.str模組代號 === 'event'; });
  if (!bool已開通) {
    顯示無法使用('本精舍尚未開通法會活動',
      obj身分.str角色 === '精舍管理員' ? '請到入口頁的「精舍設定 → 功能開通」開通「法會活動」。' : '請洽精舍管理員到「精舍設定」開通「法會活動」。');
    return;
  }

  取得元素('問候').textContent = `${obj身分.str姓名 || obj身分.str帳號}，您好　`;
  const el角色 = document.createElement('span');
  el角色.className = '小字';
  el角色.textContent = obj身分.str角色;
  取得元素('問候').appendChild(el角色);

  // 清空舊資料（換帳號重新登入時）
  obj頁面狀態.obj已載入 = {};
  obj頁面狀態.obj載入中 = {};
  obj頁面狀態.arr承辦人選項 = null;
  obj頁面狀態.str目前分頁 = '';
  arr法會分頁.forEach(function (str分頁) { 取得元素(`內容_${str分頁}`).innerHTML = ''; });
  切換狀態('已登入');

  let str初始 = '';
  try { str初始 = decodeURIComponent(window.location.hash.replace(/^#/, '')); } catch (err) { str初始 = ''; }
  切換分頁(arr法會分頁.indexOf(str初始) !== -1 ? str初始 : '活動清單');
}


