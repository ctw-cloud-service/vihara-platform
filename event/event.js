/**
 * ============================================================================
 * 函式名稱：處理新增活動
 * 版本：v1.3.0（2026-10-28）　v1.3.0：活動期間（開始＋結束日期）
 * ----------------------------------------------------------------------------
 * 用途：檢查欄位 → 呼叫 event.新增活動 → 收起表單、重畫並在卡片顯示結果。
 * 參數：el表單 {HTMLFormElement}
 * 傳回：無
 * ============================================================================
 */
function 處理新增活動(el表單) {
  const el卡片 = 取得元素('卡片_新增活動');
  清除欄位錯誤(el表單);
  const el名稱 = el表單.elements['活動名稱'];
  const el網址 = el表單.elements['來源網址'];
  if (el名稱.value.trim() === '') return 顯示並捲到訊息(el卡片, 標記欄位(el名稱, '請輸入活動名稱。'));
  // 活動期間：只填結束、或結束早於開始時擋下（yyyy-MM-dd 可直接比字串）
  const el開始 = el表單.elements['活動日期'];
  const el結束 = el表單.elements['結束日期'];
  if (el結束.value && !el開始.value) return 顯示並捲到訊息(el卡片, 標記欄位(el開始, '有填結束日期時，請一併填開始日期（單日活動只要填開始日期）。'));
  if (el結束.value && el結束.value < el開始.value) return 顯示並捲到訊息(el卡片, 標記欄位(el結束, '結束日期不能早於開始日期。'));
  if (/[[\]*?/\\:]/.test(el名稱.value)) return 顯示並捲到訊息(el卡片, 標記欄位(el名稱, '活動名稱不可含有 [ ] * ? / \\ : 這些符號。'));
  if (!/docs\.google\.com\/spreadsheets\/d\//.test(el網址.value) && !/^[\w-]{20,}$/.test(el網址.value.trim())) {
    return 顯示並捲到訊息(el卡片, 標記欄位(el網址, '請貼上回覆試算表的完整網址（https://docs.google.com/spreadsheets/d/… 開頭）。'));
  }

  const obj參數 = {
    str活動名稱: el名稱.value.trim(),
    str活動類型: el表單.elements['活動類型'].value,
    str活動日期: el表單.elements['活動日期'].value,
    str結束日期: el表單.elements['結束日期'].value,
    str來源網址: el網址.value.trim(),
    arr承辦人: 取得勾選帳號(el表單),
    str備註: el表單.elements['備註'].value.trim()
  };
  完成卡片操作(el表單.querySelector('button[type="submit"]'), 'event.新增活動', obj參數, ['活動清單', '同步與整理'],
    function () { return 取得元素('卡片_新增活動'); },
    function () { obj頁面狀態.str展開 = ''; obj頁面狀態.obj已選來源 = null; });
}


