/**
 * ============================================================================
 * 函式名稱：綁定事件
 * 版本：v1.0.0（2026-10-26）
 * ----------------------------------------------------------------------------
 * 用途：集中綁定事件。分頁內容會重畫，一律在「區塊清單」上做事件委派。
 *       toggle 事件不會冒泡，用捕捉階段。
 * 參數：無
 * 傳回：無
 * ============================================================================
 */
function 綁定事件() {
  取得元素('登出按鈕').addEventListener('click', function () { 執行登出(this); });
  取得元素('換帳號按鈕').addEventListener('click', function () { 執行登出(this); });

  const el清單 = 取得元素('區塊清單');

  // 索引標籤
  document.querySelector('.分頁列').addEventListener('click', function (e) {
    const el標籤 = e.target.closest('.分頁[data-區塊]');
    if (el標籤) 切換分頁(el標籤.dataset.區塊);
  });
  document.querySelector('.分頁列').addEventListener('keydown', 處理分頁按鍵);

  // 展開：新增活動、設定承辦人（一次只展開一個；第一次展開時讀承辦人選項）
  el清單.addEventListener('toggle', function (e) {
    const el = e.target;
    if (!el.matches || !el.matches('details[data-展開]')) return;
    const str鍵 = el.dataset.展開;
    if (el.open) {
      obj頁面狀態.str展開 = str鍵;
      el清單.querySelectorAll('details[data-展開][open]').forEach(function (el其他) { if (el其他 !== el) el其他.open = false; });
      確保承辦人選項(el);
    } else if (obj頁面狀態.str展開 === str鍵) {
      obj頁面狀態.str展開 = '';
    }
  }, true);

  // 按鈕
  el清單.addEventListener('click', function (e) {
    const el按鈕 = e.target.closest('button[data-動作]');
    if (!el按鈕) return;
    switch (el按鈕.dataset.動作) {
      case '重新讀取': 顯示分頁時載入(el按鈕.dataset.分頁); break;
      case '複製系統帳號': 複製系統帳號(el按鈕); break;
      case '選擇回覆試算表': 處理選擇回覆試算表(el按鈕); break;
      case '同步活動': case '看提醒': case '設為結束': case '重新開啟': case '看點名': 處理活動按鈕(el按鈕); break;
      case '產生點名': case '領隊代號表': case '匯出點名': case '轉為正式': case '退回演練': case '清除點名': 處理點名按鈕(el按鈕); break;
      case '檢查新報名': case '同步全部': 處理同步按鈕(el按鈕); break;
      case '處理提醒': 處理提醒按鈕(el按鈕); break;
      case '查詢重複': case '移除重複': case '重設標示': 處理重複按鈕(el按鈕); break;
      default: break;
    }
  });

  // 勾選與下拉選單
  el清單.addEventListener('change', function (e) {
    const el = e.target;
    if (el.dataset.切換 === '顯示已結束') { obj頁面狀態.bool顯示已結束 = el.checked; 畫活動清單(); return; }
    if (el.dataset.切換 === '顯示已結束點名') { obj頁面狀態.bool顯示已結束點名 = el.checked; 畫大車點名(); return; }
    if (el.dataset.切換 === '含已處理') {
      obj頁面狀態.bool含已處理 = el.checked;
      obj頁面狀態.obj已載入['同步與整理'] = false;
      顯示分頁時載入('同步與整理');
      return;
    }
    if (el.dataset.選擇 === '重複活動') {
      obj頁面狀態.str重複活動ID = el.value;
      obj頁面狀態.obj重複結果 = null;
      畫同步與整理();
    }
  });

  // 表單
  el清單.addEventListener('submit', function (e) {
    const el表單 = e.target.closest('form[data-表單]');
    if (!el表單) return;
    e.preventDefault();
    if (el表單.dataset.表單 === '新增活動') 處理新增活動(el表單);
    if (el表單.dataset.表單 === '設定承辦人') 處理設定承辦人(el表單);
  });
}


